/** Has real npm lock the old versions, then moves the project back to its own ranges. */
async function createNpmLock() {
  project.write('package.json', {
    ...MAIN,
    dependencies: { lib: '1.0.0', '@scope/lib': '1.0.0', other: '1.0.0' },
    overrides: { deep: '1.0.0' },
  });
  const args = ['install', '--package-lock-only', '--no-audit', '--no-fund'];
  const result = await exec('npm', args);
  expect(result.status, result.stderr).toBe(0);
  project.write('package.json', MAIN);
  const lock = project.readJson('package-lock.json');
  lock.packages[''].dependencies = MAIN.dependencies;
  project.write('package-lock.json', lock);
}

const LOCKS: Array<[string, () => Promise<void> | void, string]> = [
  ['npm', createNpmLock, 'package-lock.json'],
  ['Yarn 1', () => project.write('yarn.lock', YARN_1), 'yarn.lock'],
  ['Yarn 2+', () => project.write('yarn.lock', YARN_MODERN), 'yarn.lock'],
];

describe('lock files', { timeout: 60000 }, () => {
  it('uses the newest versions without one', async () => {
    expect(await install('lib')).toMatchObject({ lockfile: null });
    expect([installed('lib'), installed('deep')]).toEqual(['1.1.0', '1.2.0']);
  });

  describe.each(LOCKS)('from %s', (_name, createLock, file) => {
    beforeEach(() => createLock());

    it('pins requested and transitive packages, and installs nothing else', async () => {
      const output = await install('lib', '@scope/lib');
      expect(output).toMatchObject({
        lockfile: file,
        packages: [
          { name: 'lib', version: '1.0.0' },
          { name: '@scope/lib', version: '1.0.0' },
        ],
      });
      for (const [name, version] of Object.entries(OLD)) {
        expect(installed(name), name).toBe(version);
      }
      expect(installed('other')).toBeUndefined();
    });

    it('reports the pinned version on a dry run', async () => {
      const output = await install('lib', '--dry-run');
      expect(output.packages).toEqual([{ name: 'lib', version: '1.0.0' }]);
      expect(installed('lib')).toBeUndefined();
    });

    it('lets an explicit version win, keeping the transitive pin', async () => {
      await install('lib@1.1.0');
      expect([installed('lib'), installed('deep')]).toEqual(['1.1.0', '1.0.0']);
    });

    it('ignores the lock with --no-lockfile', async () => {
      expect(await install('lib', '--no-lockfile')).toMatchObject({ lockfile: null });
      expect([installed('lib'), installed('deep')]).toEqual(['1.1.0', '1.2.0']);
    });
  });

  it('does not create a lock file', async () => {
    await install('lib');
    expect(Object.keys(project.snapshot())).toEqual(['package.json']);
  });
});

describe('overrides', { timeout: 60000 }, () => {
  it.each([
    ['npm overrides', { overrides: { deep: '1.1.0' } }],
    ['nested npm overrides', { overrides: { lib: { deep: '1.1.0' } } }],
    ['npm $references', { overrides: { deep: '$deep' }, devDependencies: { deep: '1.1.0' } }],
    ['Yarn resolutions', { resolutions: { deep: '1.1.0' } }],
    ['Yarn nested resolutions', { resolutions: { 'lib/deep': '1.1.0' } }],
    ['Yarn 1 glob resolutions', { resolutions: { '**/lib/**/deep': '1.1.0' } }],
    ['Yarn 2+ resolutions', { resolutions: { 'deep@npm:^1.0.0': 'npm:1.1.0' } }],
  ])('applies %s to transitive packages', async (_name, extra) => {
    project.write('package.json', { ...MAIN, ...extra });
    await install('lib');
    expect(installed('deep')).toBe('1.1.0');
  });

  it('applies resolutions on top of a Yarn lock', async () => {
    project.write('package.json', { ...MAIN, resolutions: { deep: '1.1.0' } });
    project.write('yarn.lock', YARN_1);
    await install('lib');
    expect([installed('lib'), installed('deep')]).toEqual(['1.0.0', '1.1.0']);
  });

  it.each([['lib'], ['lib@1.1.0']])('does not conflict with the requested %s', async spec => {
    project.write('package.json', {
      ...MAIN,
      overrides: { lib: '^1.0.0', 'lib@^1': '^1.0.0', deep: '1.1.0' },
    });
    await install(spec);
    expect([installed('lib'), installed('deep')]).toEqual(['1.1.0', '1.1.0']);
  });
});

describe('workspaces', { timeout: 60000 }, () => {
  it('keeps the name of the link npm creates for a member', async () => {
    project.write('package.json', { private: true, workspaces: ['packages/*'] });
    const member = { name: 'member', version: '1.0.0', dependencies: { lib: '^1.0.0' } };
    project.write('packages/member/package.json', member);

    const cwd = project.resolve('packages/member');
    const result = await exec(process.execPath, [CLI, 'install', 'lib'], cwd);

    expect(result.status, result.stderr).toBe(0);
    expect(installed('lib')).toBe('1.1.0');
    expect(project.exists('node_modules/member')).toBe(true);
    expect(project.exists('node_modules/pici-temp')).toBe(false);
    expect(project.readJson('packages/member/package.json')).toEqual(member);
  });
});

describe('without a package.json', { timeout: 60000 }, () => {
  it('installs explicit versions and leaves no files behind', async () => {
    const { rmSync } = await import('node:fs');
    rmSync(project.resolve('package.json'));
    await install('lib@1.0.0');
    expect(installed('lib')).toBe('1.0.0');
    expect(project.snapshot()).toEqual({});
  });
});
